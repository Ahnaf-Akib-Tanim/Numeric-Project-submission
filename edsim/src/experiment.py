"""
experiment.py -- replication driver.

Responsibilities
----------------
  * turn a (config, policy-spec, seed) triple into one RunResult
  * run N replications, optionally across processes
  * implement the CRN / independent-streams switch of WP5
  * cache patient streams inside each worker so that repeated evaluations at
    the same seeds (grid search, Nelder-Mead) do not re-sample arrivals

Policies are passed around as *specs* -- ``("SBP", {"k1": 13.1, "k2": 2.1})`` --
rather than as objects, because specs are trivially picklable and hashable,
which is what ``ProcessPoolExecutor`` on Windows (spawn start method) needs.
"""
from __future__ import annotations

import atexit
import os
from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

from . import config as C
from .console import Progress
from .engine import simulate
from .metrics import RunResult
from .policies import make_policy
from .rng import clone_stream, generate_patient_stream, replication_seed

PolicySpec = Tuple[str, dict]


# ---------------------------------------------------------------------------
# Per-worker patient-stream cache
# ---------------------------------------------------------------------------
_STREAM_CACHE: Dict[tuple, list] = {}
_CACHE_LIMIT = 512


def _get_stream(cfg: C.SimConfig, seed: int):
    # Keyed on the EXOGENOUS part of the config only -- see SimConfig.stream_key.
    key = (cfg.stream_key(), seed)
    st = _STREAM_CACHE.get(key)
    if st is None:
        if len(_STREAM_CACHE) >= _CACHE_LIMIT:
            _STREAM_CACHE.clear()
        st = generate_patient_stream(cfg, seed)
        _STREAM_CACHE[key] = st
    return st


def clear_stream_cache() -> None:
    _STREAM_CACHE.clear()


# ---------------------------------------------------------------------------
# A single, reused process pool
# ---------------------------------------------------------------------------
# Windows uses the *spawn* start method: every worker re-imports the package,
# which costs ~0.3 s each.  Creating a pool per batch made a 36-simulation run
# spend more time starting processes than simulating.  We therefore keep ONE
# pool alive for the whole script.  Reusing it also keeps each worker's
# _STREAM_CACHE warm, which is what makes the grid search and Nelder-Mead
# affordable: the same seeds are re-used at every candidate (k1, k2), so the
# arrival streams are sampled once per worker and then reused thousands of times.
_POOL = None
_POOL_WORKERS = 0

#: Below this many jobs the pool's dispatch/pickle overhead outweighs the
#: parallel speed-up, so the batch is run in-process instead.  Measured on this
#: machine: at 25 jobs parallel is already ~1.7x faster, at 8 jobs it is slower.
SERIAL_THRESHOLD = 24


def get_pool(workers: int):
    global _POOL, _POOL_WORKERS
    if workers is None or workers <= 1:
        return None
    if _POOL is None or _POOL_WORKERS != workers:
        shutdown_pool()
        _POOL = ProcessPoolExecutor(max_workers=workers)
        _POOL_WORKERS = workers
    return _POOL


def shutdown_pool() -> None:
    global _POOL, _POOL_WORKERS
    if _POOL is not None:
        _POOL.shutdown(wait=True)
    _POOL = None
    _POOL_WORKERS = 0


atexit.register(shutdown_pool)


def _map_jobs(jobs, workers, progress):
    """Run ``jobs`` through the shared pool, or serially when that is cheaper."""
    out = []
    pool = get_pool(workers) if len(jobs) >= SERIAL_THRESHOLD else None
    if pool is not None:
        chunk = max(1, len(jobs) // (workers * 8) or 1)
        for r in pool.map(_task, jobs, chunksize=chunk):
            out.append(r)
            if progress:
                progress.update(1)
    else:
        for j in jobs:
            out.append(_task(j))
            if progress:
                progress.update(1)
    return out


# ---------------------------------------------------------------------------
# One replication
# ---------------------------------------------------------------------------
def run_one(cfg: C.SimConfig, spec: PolicySpec, seed: int,
            keep_raw: bool = False, record_history: bool = False) -> RunResult:
    """Simulate one replication of one policy on the stream generated by ``seed``."""
    key, kwargs = spec
    policy = make_policy(key, **kwargs)
    stream = clone_stream(_get_stream(cfg, seed))
    res = simulate(cfg, policy, stream, record_history=record_history,
                   keep_raw=keep_raw)
    res.seed = seed
    return res


def _task(args):
    cfg, spec, seed, keep_raw = args
    return run_one(cfg, spec, seed, keep_raw=keep_raw)


# ---------------------------------------------------------------------------
# Many replications, one policy
# ---------------------------------------------------------------------------
def run_replications(cfg: C.SimConfig, spec: PolicySpec, n_reps: int,
                     base_seed: int = C.BASE_SEED, crn: bool = True,
                     workers: Optional[int] = None, keep_raw: bool = False,
                     progress: Optional[Progress] = None) -> List[RunResult]:
    """Run ``n_reps`` replications of one policy.

    ``crn=True``  -> seeds are ``f(base_seed, rep)`` only, so the same seeds are
                     reused by every policy: Common Random Numbers.
    ``crn=False`` -> the policy key is mixed into the seed: independent streams.
    """
    key = spec[0]
    seeds = [replication_seed(base_seed, r, key, crn) for r in range(n_reps)]
    jobs = [(cfg, spec, s, keep_raw) for s in seeds]
    return _map_jobs(jobs, workers or 0, progress)


# ---------------------------------------------------------------------------
# Many replications, many policies (the standard comparison call)
# ---------------------------------------------------------------------------
def run_comparison(cfg: C.SimConfig, specs: Dict[str, PolicySpec], n_reps: int,
                   base_seed: int = C.BASE_SEED, crn: bool = True,
                   workers: Optional[int] = None, keep_raw: bool = False,
                   label: str = "simulating",
                   progress: Optional[Progress] = None) -> Dict[str, List[RunResult]]:
    """Run every policy in ``specs`` over ``n_reps`` replications.

    With ``crn=True`` the returned lists are *paired*: element r of every policy
    used exactly the same patient stream, which is what makes the paired t-test
    of Sec 3.3.1 valid and what WP5 exploits for variance reduction.
    """
    total = len(specs) * n_reps
    own_bar = progress is None
    prog = Progress(total, label) if own_bar else progress
    # Build ONE job list across all policies so the pool is filled once and the
    # per-worker stream cache is shared between policies (CRN reuses seeds).
    jobs = []
    for name, spec in specs.items():
        for r in range(n_reps):
            jobs.append((cfg, spec, replication_seed(base_seed, r, spec[0], crn),
                         keep_raw))
    flat = _map_jobs(jobs, workers or 0, prog)
    if own_bar:
        prog.close()
    out: Dict[str, List[RunResult]] = {}
    for i, name in enumerate(specs):
        out[name] = flat[i * n_reps:(i + 1) * n_reps]
    return out


# ---------------------------------------------------------------------------
# Batch evaluation used by the optimisers (many specs, shared seeds)
# ---------------------------------------------------------------------------
@dataclass
class EvalBudget:
    """Counts how much simulation an optimiser actually consumed.

    This is the headline efficiency number of WP3: grid search vs Nelder-Mead
    is compared on ``n_simulations`` (one full week-long replication each), not
    on wall-clock, so the comparison is hardware-independent.
    """
    n_evaluations: int = 0       # distinct (k1,k2) points evaluated
    n_simulations: int = 0       # total week-long replications run

    def add(self, n_reps: int) -> None:
        self.n_evaluations += 1
        self.n_simulations += n_reps


def evaluate_points(cfg: C.SimConfig, policy_key: str, points: Sequence[dict],
                    n_reps: int, base_seed: int = C.BASE_SEED,
                    workers: Optional[int] = None,
                    progress: Optional[Progress] = None) -> List[List[RunResult]]:
    """Evaluate many parameter settings, each over the SAME ``n_reps`` seeds.

    Using identical seeds for every candidate is CRN applied to *optimisation*:
    it removes seed noise from the comparison between candidate (k1,k2) pairs
    and makes the response surface far smoother, which is what allows a
    derivative-free method like Nelder-Mead to work at all on a stochastic
    objective.
    """
    seeds = [replication_seed(base_seed, r, policy_key, True) for r in range(n_reps)]
    jobs = [(cfg, (policy_key, pt), s, False) for pt in points for s in seeds]
    results = _map_jobs(jobs, workers or 0, progress)
    return [results[i * n_reps:(i + 1) * n_reps] for i in range(len(points))]


def default_workers() -> int:
    """Leave two cores for the OS / the user's editor."""
    return max(1, (os.cpu_count() or 2) - 2)
